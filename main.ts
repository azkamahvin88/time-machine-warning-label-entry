import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ENTRY =
  "WARNING: Do not bring souvenirs from the Cretaceous. The pebble in your pocket is an egg, and it is hatching.";

const outDir = process.env.MAKEFUN_OUTPUT_DIR ?? "/output";

// The gate is 1-120 characters of UTF-8 text: fail loudly rather than
// silently shipping an entry the judge can never see.
if ([...ENTRY].length === 0 || [...ENTRY].length > 120) {
  throw new Error(`entry is ${[...ENTRY].length} characters, must be 1-120`);
}
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "entry.txt"), ENTRY + "\n", "utf8");
